# ============================================================
# CALORIE & NUTRITION TARGET SERVICE
# ============================================================


def calculate_nutrition_targets(
    age: int,
    gender: str,
    height_cm: float,
    weight_kg: float,
    activity_level: str,
    goal: str,
    women_health_condition: str | None = None,
):
    """
    Calculate estimated BMR, TDEE,
    daily calorie target and macro targets.

    Women's health conditions are used as additional
    nutrition context.

    Important:
    Pregnancy and breastfeeding have different nutritional
    requirements that depend on factors not currently
    collected by MealMind.

    Therefore, this prototype does NOT automatically apply
    normal weight-loss or weight-gain calorie adjustments
    during pregnancy or breastfeeding.
    """

    gender = (
        gender.lower().strip()
        if gender
        else ""
    )

    activity_level = (
        activity_level.lower().strip()
        if activity_level
        else "sedentary"
    )

    goal = (
        goal.lower().strip()
        if goal
        else "maintenance"
    )

    women_health_condition = (
        women_health_condition.lower().strip()
        if women_health_condition
        else "none"
    )


    # ========================================================
    # 1. CALCULATE BMR
    # Mifflin-St Jeor Equation
    # ========================================================

    if gender == "male":

        bmr = (
            (10 * weight_kg)
            + (6.25 * height_cm)
            - (5 * age)
            + 5
        )

    elif gender == "female":

        bmr = (
            (10 * weight_kg)
            + (6.25 * height_cm)
            - (5 * age)
            - 161
        )

    else:

        # Temporary neutral fallback for prototype.
        #
        # This should eventually be replaced by a more
        # appropriate user-specific calculation strategy.

        bmr = (
            (10 * weight_kg)
            + (6.25 * height_cm)
            - (5 * age)
            - 78
        )


    # ========================================================
    # 2. ACTIVITY MULTIPLIER
    # ========================================================

    activity_multipliers = {
        "sedentary": 1.2,
        "light": 1.375,
        "moderate": 1.55,
        "active": 1.725,
        "very_active": 1.9,
    }

    activity_multiplier = (
        activity_multipliers.get(
            activity_level,
            1.2
        )
    )


    # ========================================================
    # 3. CALCULATE ESTIMATED TDEE
    # ========================================================

    tdee = (
        bmr *
        activity_multiplier
    )


    # ========================================================
    # 4. IDENTIFY SPECIAL WOMEN'S HEALTH CONTEXT
    # ========================================================

    is_pregnant = (
        gender == "female"
        and women_health_condition == "pregnancy"
    )

    is_breastfeeding = (
        gender == "female"
        and women_health_condition == "breastfeeding"
    )

    requires_special_energy_guidance = (
        is_pregnant
        or is_breastfeeding
    )


    # ========================================================
    # 5. GOAL-BASED CALORIE TARGET
    # ========================================================
    #
    # Standard users:
    #
    # Weight loss:
    # TDEE - 400 kcal
    #
    # Weight / muscle / strength gain:
    # TDEE + 300 kcal
    #
    # Maintenance:
    # TDEE
    #
    #
    # Pregnancy / Breastfeeding:
    #
    # We intentionally do NOT automatically apply the
    # standard weight-loss or weight-gain adjustment.
    #
    # Precise requirements depend on additional information
    # that MealMind does not currently collect.
    # ========================================================

    if requires_special_energy_guidance:

        target_calories = tdee

    elif goal in [
        "weight_loss",
        "weight loss",
        "lose_weight",
        "lose weight",
    ]:

        target_calories = (
            tdee - 400
        )

    elif goal in [
        "weight_gain",
        "weight gain",
        "gain_weight",
        "gain weight",
        "muscle_gain",
        "muscle gain",
        "strength_gain",
        "strength gain",
    ]:

        target_calories = (
            tdee + 300
        )

    else:

        target_calories = tdee


    # ========================================================
    # 6. BASIC CALORIE SAFETY FLOOR
    # ========================================================
    #
    # Prevent obviously very low calorie targets from being
    # generated by the simple prototype calculation.
    #
    # This is only a guardrail and NOT a medical prescription.
    # ========================================================

    if not requires_special_energy_guidance:

        if gender == "female":

            target_calories = max(
                target_calories,
                1200
            )

        elif gender == "male":

            target_calories = max(
                target_calories,
                1500
            )

        else:

            target_calories = max(
                target_calories,
                1200
            )


    # ========================================================
    # 7. PROTEIN TARGET
    # ========================================================
    #
    # We continue using a simple body-weight-based estimate
    # for the prototype.
    #
    # Pregnancy and breastfeeding are intentionally not given
    # a custom clinical protein prescription here.
    # ========================================================

    if requires_special_energy_guidance:

        protein_per_kg = 1.4

    elif goal in [
        "weight_loss",
        "weight loss",
        "lose_weight",
        "lose weight",
    ]:

        protein_per_kg = 1.6

    elif goal in [
        "muscle_gain",
        "muscle gain",
        "strength_gain",
        "strength gain",
    ]:

        protein_per_kg = 1.8

    else:

        protein_per_kg = 1.4


    protein_g = (
        weight_kg *
        protein_per_kg
    )


    # ========================================================
    # 8. FAT TARGET
    # ========================================================

    # Approximately 25% of daily calories from fat.

    fat_calories = (
        target_calories *
        0.25
    )

    fat_g = (
        fat_calories /
        9
    )


    # ========================================================
    # 9. CARBOHYDRATE TARGET
    # ========================================================

    protein_calories = (
        protein_g *
        4
    )

    remaining_calories = (
        target_calories
        - protein_calories
        - fat_calories
    )

    # Prevent negative carbohydrate calculations
    # in unusual edge cases.

    remaining_calories = max(
        remaining_calories,
        0
    )

    carbohydrates_g = (
        remaining_calories /
        4
    )


    # ========================================================
    # 10. FIBER TARGET
    # ========================================================

    # General prototype approximation:
    # 14 g fiber per 1000 kcal.

    fiber_g = (
        target_calories /
        1000
    ) * 14


    # ========================================================
    # 11. RETURN TARGETS
    # ========================================================

    return {
        "bmr":
            round(bmr),

        "tdee":
            round(tdee),

        "target_calories":
            round(target_calories),

        "protein_g":
            round(protein_g),

        "carbohydrates_g":
            round(carbohydrates_g),

        "fat_g":
            round(fat_g),

        "fiber_g":
            round(fiber_g),
    }